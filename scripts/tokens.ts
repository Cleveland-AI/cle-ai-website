// Generates src/styles/tokens.css from theme-source/cle-ai-theme/theme.json.
// Variable names and values are exactly what WordPress emits for the theme, so the ported
// theme CSS works unchanged. Run with `npm run tokens`; the output is committed.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const themePath = resolve(here, "../theme-source/cle-ai-theme/theme.json");
const outPath = resolve(here, "../src/styles/tokens.css");

type Preset = { slug: string; color?: string; size?: string; fontFamily?: string };

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

/** Nested object -> [`a--b-c`, value] pairs, the way WordPress names --wp--custom-- variables. */
function flatten(obj: Record<string, unknown>, path: string[] = []): [string, string][] {
  return Object.entries(obj).flatMap(([key, value]): [string, string][] =>
    value !== null && typeof value === "object"
      ? flatten(value as Record<string, unknown>, [...path, kebab(key)])
      : [[[...path, kebab(key)].join("--"), String(value)]],
  );
}

type Theme = {
  settings: {
    color: { palette: Preset[] };
    typography: { fontSizes: Preset[]; fontFamilies: Preset[] };
    spacing: { spacingSizes: Preset[] };
    custom: Record<string, unknown>;
    layout: { contentSize: string; wideSize: string };
  };
};

export function buildTokens(theme: Theme): string {
  const s = theme.settings;
  const decl: [string, string][] = [];
  const presets = (kind: string, items: Preset[], field: "color" | "size" | "fontFamily") =>
    items.forEach((p) => decl.push([`--wp--preset--${kind}--${p.slug}`, p[field] as string]));

  presets("color", s.color.palette, "color");
  presets("font-size", s.typography.fontSizes, "size");
  presets("font-family", s.typography.fontFamilies, "fontFamily");
  presets("spacing", s.spacing.spacingSizes, "size");
  for (const [name, value] of flatten(s.custom)) decl.push([`--wp--custom--${name}`, value]);

  const lines = decl.map(([n, v]) => `\t${n}: ${v};`).join("\n");
  return `/* Generated by scripts/tokens.ts from theme-source/cle-ai-theme/theme.json. Do not edit; run \`npm run tokens\`. */
:root {
${lines}
\t--wp--style--global--content-size: ${s.layout.contentSize};
\t--wp--style--global--wide-size: ${s.layout.wideSize};
}
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const theme = JSON.parse(readFileSync(themePath, "utf8"));
  writeFileSync(outPath, buildTokens(theme));
  console.log(`wrote ${outPath}`);
}
