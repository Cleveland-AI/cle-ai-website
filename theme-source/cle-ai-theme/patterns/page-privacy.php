<h2 class="wp-block-heading">Your choices</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>You can do any of these by emailing <a href="mailto:info@cle-ai.com">info@cle-ai.com</a>. We'll answer within 30 days, usually sooner.</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li><strong>Unsubscribe</strong> from the newsletter with the link at the bottom of any email. We'll still send you a confirmation or essential notice about an event you registered for.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Ask what we have.</strong> We'll tell you what personal information we hold about you and send you a copy.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Correct it.</strong> Tell us what's wrong and we'll fix it.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Delete it.</strong> We'll delete your information unless we need to keep some of it, for example a donation record for tax purposes or a signed release. We'll tell you what we kept and why.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Opt out of photos and recordings.</strong> See the section above. Ask at check-in or email us afterward.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Opt out of demographic questions.</strong> They're always optional. Choose "prefer not to say" or skip them.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Give anonymously.</strong> Tell us at the time of your gift, or choose the anonymous option on Givebutter, and we won't name you publicly.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p>If you live somewhere with privacy laws that give you additional rights, such as the European Union, the United Kingdom or a U.S. state with a comprehensive privacy law, you can exercise them through the same address. We're a small volunteer organization based in Ohio and don't target those regions, but we'll honor reasonable requests from anyone.</p>
