<h2 class="wp-block-heading">How we use information and who sees it</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>We use what we collect to run events, keep in touch, improve our programs, thank supporters, and report on our work. We don't sell personal information, and we don't rent or trade our lists.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">We share information with</h3>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li><strong>Service providers</strong> that help us operate: website hosting, email newsletter, event registration, payment processing, video hosting, and survey tools. They can use your information only to provide the service to us.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Co-hosts and venues</strong> for a specific event, limited to what they need, such as a headcount or a check-in list for building security.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Funders and grant makers</strong>, in aggregate only: how many people attended, where they came from by ZIP code or county, first-time attendees, survey results, and demographic totals. We don't give funders names or individual answers.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Sponsors</strong>, who receive attendance numbers and event photos. We don't give sponsors attendee lists, email addresses or contact details. If you want a sponsor to contact you, you give them your details yourself.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>The public</strong>, through photos, recordings and stories as described above, and through public acknowledgment of donors and sponsors who agree to be named. You can give anonymously.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Authorities</strong>, if the law requires it, or to protect the safety of attendees, volunteers or the organization.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

