<h2 class="wp-block-heading">Who we are and what this covers</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Cleveland AI and Data ("CLE AI &amp; DATA," "we," "us") is an Ohio nonprofit corporation and a 501(c)(3) public charity. We run free talks, workshops, socials and an annual Mega Meetup, and we publish a website at cle-ai.com.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>This policy explains what information we collect when you visit our website, join our community, register for or attend an event, or support us, and what we do with it. It also explains how we handle photos, video and recordings at events, since we often record and publish them.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>It applies to:</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>cle-ai.com and any pages we run on it</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>our newsletter and email lists</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>event registration, whether on our site or through a platform such as Meetup, Eventbrite or Luma</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>in-person and online events we host or co-host</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>donations and sponsorships</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p>It does not cover the platforms themselves. Meetup, Discord, Eventbrite, Givebutter, YouTube and similar services have their own privacy policies, and what you share there is governed by those.</p>
