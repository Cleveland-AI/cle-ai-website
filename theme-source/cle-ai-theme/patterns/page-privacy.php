<h3 class="wp-block-heading">Children</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Our events are designed for adults. People under 18 are welcome at most events with a parent or guardian, but we don't knowingly collect personal information from anyone under 13, and we don't publish identifiable photos of minors without a parent's written permission. If you believe a child has given us information, email <a href="mailto:info@cle-ai.com">info@cle-ai.com</a> and we'll delete it. Youth-specific programs, if we run them, will have their own registration and consent forms.</p>
