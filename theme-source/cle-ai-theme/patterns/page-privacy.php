<h2 class="wp-block-heading">Photos, video and recordings at events</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>We photograph and record our events, and we publish what we capture. That's how we show funders, sponsors and future attendees what we do. Here is how it works.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">What we capture</h3>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Photos of the room, speakers, demo tables and groups of attendees.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Video and audio of talks, panels and Q&amp;A. Online events may be recorded in full, including the chat.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Livestreams of some events, which are recorded.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Screenshots of online events.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Where it may be published</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Our website, newsletter, social media accounts (such as LinkedIn, YouTube, Instagram and X), Meetup, Discord, grant reports, sponsor reports, the annual prospectus and printed materials. Recordings of talks may stay online indefinitely.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">How consent works</h3>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li><strong>Attendees.</strong> Registering for or attending an event means you agree that you may appear in photos and recordings, and that we may publish them for the purposes above without payment to you. We tell you this at registration and with signs at the venue.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Speakers and panelists.</strong> We ask speakers to confirm in writing that we may record and publish their talk, bio, headshot and slides. Speakers keep ownership of their slides and content; we get a non-exclusive license to publish them.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Q&amp;A.</strong> If you ask a question at a recorded session, your voice and possibly your face may be in the recording. If you'd rather not be recorded, ask your question before or after, or in writing.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Online events.</strong> Turning on your camera or microphone in a recorded session means you may appear in the recording. You can keep them off.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">If you don't want to be in it</h3>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Tell a volunteer at check-in. We'll give you a way to identify yourself to the photographer, such as a colored lanyard or sticker, and the photographer will avoid you where possible.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Sit outside the recorded area at talks. We mark where the camera points.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Email <a href="mailto:info@cle-ai.com">info@cle-ai.com</a> after an event and we'll remove or blur you from photos we control, and from future publications, as far as we reasonably can. We can't recall copies others have already downloaded or shared, and we may not be able to edit a continuous recording of a talk.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">What we won't do</h3>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Use your image to suggest you endorse a sponsor or product.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Publish your name alongside your image without asking, unless you're a speaker, panelist, volunteer, award recipient or sponsor representative acting in that role.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Record private conversations, hallway chats or social events in a way that captures what's said. Socials and hikes get photos, not audio.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Photograph children in a way that identifies them. See Children below.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

